// Grounded, browser-only knowledge responses. This module does NOT pretend that
// a tiny randomly initialized model can answer complex factual questions.
// It retrieves readable Wikipedia extracts and links to the original article.
const ENDPOINT = 'https://en.wikipedia.org/w/api.php';
const STOP = new Set('a an the what who whom whose when why how where which is was were are do does did can could should would will please tell me about explain describe give information overview of to for on in and it this that i want know more much many some me you your i am'.split(' '));
const normalize = value => String(value || '').replace(/\s+/g, ' ').trim();
const urlFor = title => `https://en.wikipedia.org/wiki/${encodeURIComponent(title.replace(/ /g, '_'))}`;
const plain = text => normalize(text).replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F\uFFFD]/g, '');

export function queryFromMessage(request = {}) {
  const prompt = normalize(request.prompt).slice(0, 300);
  const followUp = /^(tell me more|more details|elaborate|explain more|continue|what about that)\s*[.?!]*$/i.test(prompt);
  if (followUp) {
    const history = Array.isArray(request.messages) ? request.messages.slice(-8) : [];
    const lastSource = [...history].reverse().find(m => m.role === 'assistant' && /en\.wikipedia\.org\/wiki\//.test(m.content || ''));
    if (lastSource) {
      const match = /en\.wikipedia\.org\/wiki\/([^\s)]+)/.exec(lastSource.content);
      if (match) return {query: decodeURIComponent(match[1]).replace(/_/g, ' '), more: true};
    }
  }
  let q = prompt
    .replace(/^(?:please\s+)?(?:can you|could you|would you)\s+(?:please\s+)?/i, '')
    .replace(/^(?:tell me about|give me (?:information|facts) (?:on|about)|explain(?: to me)?|describe|what (?:is|are|was|were)|what's|who (?:is|was|were)|who's|when (?:was|did|is)|where (?:is|was|are)|how (?:does|do|did)|why (?:does|do|did|is|are))\s+/i, '')
    .replace(/\b(?:in simple words|in detail|briefly|for me|please)\b/gi, '')
    .replace(/[?!.,:;]+$/g, '').trim();
  if (q.length < 3) q = prompt.replace(/[?!.,:;]+$/g, '').trim();
  // If all words are instructional stopwords, retain the original query.
  if (q.split(/\s+/).every(word => STOP.has(word.toLowerCase()))) q = prompt;
  return {query: q.slice(0, 250), more: false};
}

function canned(prompt) {
  const p = normalize(prompt).toLowerCase().replace(/[!?.,]+$/g, '');
  if (/^(hi|hello|hey|good morning|good evening|good afternoon|yo)$/.test(p))
    return 'Hello! I’m Kira. Ask me a factual question, and I’ll look up information on Wikipedia. My experimental Transformer can continue learning in the background.';
  if (/^(thank you|thanks|thank u|thx)$/.test(p))
    return 'You’re welcome! What would you like to explore next?';
  if (/^(who are you|what are you|what can you do)$/.test(p))
    return 'I’m Kira, a browser-only Wikipedia research assistant with a separate experimental Transformer. I can find and show sourced Wikipedia information while the local neural network continues training. Wikipedia answers are retrieved, not generated by the neural network.';
  if (/^(how are you|how's it going)$/.test(p))
    return 'I’m ready to help you explore a topic. What would you like to know?';
  return null;
}

export async function mediaWikiFetch(params, fetcher = fetch) {
  const url = new URL(ENDPOINT);
  for (const [key, value] of Object.entries({action:'query',format:'json',formatversion:'2',origin:'*',...params})) url.searchParams.set(key, String(value));
  const response = await fetcher(url.toString(), {mode:'cors',cache:'no-store',signal:AbortSignal.timeout(16000)});
  if (!response.ok) throw new Error(`Wikipedia returned HTTP ${response.status}`);
  const data = await response.json();
  if (data.error) throw new Error(data.error.info || 'Wikipedia API error');
  return data;
}

function articleScore(title, query) {
  const t = title.toLowerCase(), q = query.toLowerCase().trim();
  if(t === q)return 100;
  if(t.startsWith(q))return 65;
  if(t.includes(q))return 45;
  const words=q.split(/\W+/).filter(w=>w.length>2&&!STOP.has(w));
  return words.reduce((s,w)=>s+(t.includes(w)?5:0),0);
}

export function readableExtract(extract, long = false) {
  const raw = String(extract || '').replace(/\r/g, '').trim();
  if (!raw) return '';
  // Avoid section titles and abrupt mid-sentence truncation.
  const paragraphs = raw.split(/\n\s*\n/).map(p => p.replace(/\s*\n\s*/g,' ').trim()).filter(p=>p.length>45&&!/^={2,}/.test(p));
  const merged = (paragraphs.length ? paragraphs : [plain(raw)]).join('\n\n');
  const limit = long ? 1800 : 1100;
  if (merged.length <= limit) return merged;
  let cut = merged.slice(0, limit);
  const boundaries=[cut.lastIndexOf('. '),cut.lastIndexOf('! '),cut.lastIndexOf('? '),cut.lastIndexOf('\n\n')];
  const end=Math.max(...boundaries);
  if (end>Math.min(180,limit*.45)) cut=cut.slice(0,end+1).trim();
  else cut=cut.trimEnd()+'…';
  return cut;
}

function formatArticle(page, cached=false, more=false) {
  const title = page.title;
  const contents = readableExtract(page.extract || page.content, more);
  if (!contents) return null;
  const url = page.url || urlFor(title);
  // Keep the claim and attribution together. No invented facts or made-up quotes.
  return {text:`**${title}**\n\n${contents}\n\nSource: [Wikipedia — ${title}](${url})${cached?' · *Saved article (may be outdated)*':''}`,
    source_title:title,source_url:url,mode:cached?'cached':'wikipedia',
    generated_tokens:0,prompt_tokens:0,tokens_per_second:0,stop_reason:'sourced_answer'};
}

export async function wikiAnswer(request, {getJSON = mediaWikiFetch, cachedArticles = async () => []} = {}) {
  const prompt=normalize(request?.prompt);
  if (!prompt) throw new Error('Type a question to start chatting.');
  const start=performance.now();
  const quick=canned(prompt);
  if (quick) return {text:quick,mode:'local',generated_tokens:0,prompt_tokens:0,tokens_per_second:0,stop_reason:'local_reply',seconds:(performance.now()-start)/1000};
  const {query,more}=queryFromMessage(request);
  let trouble=null;
  try {
    const results=await getJSON({list:'search',srsearch:query,srnamespace:0,srlimit:5});
    const matches=(results.query?.search || []).filter(item => item.title && Number.isInteger(item.pageid))
      .sort((a,b)=>articleScore(b.title,query)-articleScore(a.title,query));
    if(matches.length){
      const extractParams={prop:'extracts',pageids:matches.slice(0,more?1:3).map(x=>x.pageid).join('|'),explaintext:1,exsectionformat:'plain',exlimit:more?1:3};
      if(!more)extractParams.exintro=1;
      const pages=await getJSON(extractParams);
      const pageMap=new Map((pages.query?.pages||[]).map(p=>[p.pageid,p]));
      for (const match of matches.slice(0,3)){
        const page=pageMap.get(match.pageid);
        if (!page || !page.extract || /may refer to:\s*$/i.test(page.extract.slice(0,150))) continue;
        const answer=formatArticle(page,false,more);
        if(answer){answer.seconds=(performance.now()-start)/1000;return answer;}
      }
    }
  } catch(error) {trouble=error;}
  // Offline fallback: genuinely saved Wikipedia articles in the existing IndexedDB.
  let local=[];
  try{local=await cachedArticles();}catch{/* Browser storage can be inaccessible. */}
  const ranked=local.filter(p=>p.title&&p.content&&articleScore(p.title,query)>0)
    .sort((a,b)=>articleScore(b.title,query)-articleScore(a.title,query));
  if (ranked.length){
    const answer=formatArticle(ranked[0],true,more);
    if(answer){answer.seconds=(performance.now()-start)/1000;return answer;}
  }
  const reason=trouble?'Wikipedia could not be reached.':'I could not find a useful Wikipedia article for that question.';
  return {text:`${reason} Try asking about a specific subject, person, place, or scientific concept.${trouble?' You can also retry when your connection returns.':''}`,
    mode:'unavailable',generated_tokens:0,prompt_tokens:0,tokens_per_second:0,
    stop_reason:'no_source',seconds:(performance.now()-start)/1000};
}
